    for f in (back, side, front, door, ceilingFinish):
        assert f is None or f in FIN, f
    d = {'id': id, 'type': type, 'page': page,
         'walls': {'back': back, 'side': side, 'front': front}, 'door': door,
         'ceiling': ceiling, 'ceilingFinish': ceilingFinish, 'ceilingColor': ceilingColor,
         'light': light, 'handrail': handrail, 'floor': floor}
    if decor: d['wallDecor'] = decor
    if canopy: d['canopy'] = canopy
    if landingDoor: d['landingDoor'] = landingDoor
    d['image'] = f'tools/lifts/reference/cabins/{id}.jpg'
    d['text'] = text
    if note: d['note'] = note
    return d

