def spd(v):
    return f'{v:g}' if v != int(v) else f'{v:.1f}'


def per_speed(speeds, vals):
    if not isinstance(vals, list):
        vals = [vals] * len(speeds)
    assert len(vals) == len(speeds), (speeds, vals)
    return {spd(s): v for s, v in zip(speeds, vals)}


def row(load, speeds, door, car, shaft, mr, oh, pd, doorType=None, shape=None):
    return {
        'load': load, 'speeds': speeds, 'door': door, 'doorType': doorType,
        'car': car, 'shaftSize': shaft, 'machineRoom': mr,
        'overhead': per_speed(speeds, oh), 'pit': per_speed(speeds, pd), 'shape': shape,
    }


